package com.inventory.manager.integration;

import com.inventory.manager.dto.LoginRequestDto;
import org.junit.jupiter.api.Test;
import org.springframework.http.MediaType;
import org.springframework.test.context.TestPropertySource;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

@TestPropertySource(properties = {
        "app.rate-limit.auth-max-requests=3",
        "app.rate-limit.window-seconds=60"
})
class AuthRateLimitIntegrationTest extends AbstractIntegrationTest {

    @Test
    void login_returns429_whenRateLimitExceeded() throws Exception {
        String body = objectMapper.writeValueAsString(new LoginRequestDto("admin", "wrong-password"));

        for (int i = 0; i < 3; i++) {
            mockMvc.perform(post("/api/auth/login")
                            .contentType(MediaType.APPLICATION_JSON)
                            .content(body))
                    .andExpect(status().isUnauthorized());
        }

        mockMvc.perform(post("/api/auth/login")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(body))
                .andExpect(status().isTooManyRequests())
                .andExpect(jsonPath("$.status").value(429));
    }
}
